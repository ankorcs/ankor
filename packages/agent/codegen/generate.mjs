function hookFor(kind, check, where, source) {
  const key = kind === 'super' ? check : `${kind}:${source}`;

  if (!hooks.has(key)) {
    const fn = check._zod.def.fn;
    const named = kind === 'refine' && fn.name ? fn.name : null;
    const name = HOOK_NAMES[where] ?? snake(named ?? where.replace(/#0$/, ''));

    if ([...hooks.values()].some((hook) => hook.name === name)) {
      fail(where, `duplicate hook ${name}`);
    }

    hooks.set(key, { kind, name, where, source });
  }

  return hooks.get(key).name;
}

/** The statements that parse `p` as `schema`, without its checks. */
function parse(schema, where) {
  const def = schema._zod.def;
  const err = def.error ? `Some(${rustStr(constant(def.error))})` : 'None';
  const typeIssue = (expected) => `p.push(invalid_type(${rustStr(expected)}, p.value.as_ref(), ${err}));`;

  switch (def.type) {
    case 'string':
      if (def.coerce) fail(where, 'coerce');
      return [`if !matches!(p.value, Some(Value::String(_))) { ${typeIssue('string')} }`];
    case 'number':
      if (def.coerce) fail(where, 'coerce');
      return [`if !matches!(p.value, Some(Value::Number(_))) { ${typeIssue('number')} }`];
    case 'boolean':
      return [`if !matches!(p.value, Some(Value::Bool(_))) { ${typeIssue('boolean')} }`];
    case 'unknown':
      return [];
    case 'literal':
    case 'enum': {
      const values = def.type === 'literal' ? def.values : [...schema._zod.values];
      const issue = { code: 'invalid_value', values, input: undefined };

      return [`if !(${matches(values, 'p.value.as_ref()', where)}) { p.push(Issue::new(Code::InvalidValue, ${rustStr(message(issue, def.error))}, None)); }`];
    }
    case 'object': {
      const catchall = def.catchall?._zod.def.type;

      if (catchall !== undefined && catchall !== 'unknown') fail(where, `catchall ${catchall}`);

      const lines = [
        `let Some(Value::Object(input)) = &p.value else { ${typeIssue('object')} return; };`,
        'let input = input.clone();',
        'let mut out = serde_json::Map::new();',
      ];

      for (const [key, field] of Object.entries(def.shape)) {
        if (key === '__proto__') fail(where, '__proto__ key');

        const child = fnFor(field, `${where}.${key}`);
        const optin = field._zod.optin === undefined ? 'OptIn::Required' : field._zod.optin === 'defaulted' ? 'OptIn::Defaulted' : 'OptIn::Optional';

        lines.push(`property(p, &mut out, &input, ${rustStr(key)}, ${child}, ${optin}, ${field._zod.optout === 'optional'});`);
      }

      if (catchall === 'unknown') {
        lines.push(`extra_properties(&mut out, &input, &[${Object.keys(def.shape).map(rustStr).join(', ')}]);`);
      }

      lines.push('p.value = Some(Value::Object(out));');

      return lines;
    }
    case 'array': {
      const caps = [];

      for (const ch of def.checks ?? []) {
        const cd = ch._zod.def;

        if (!/_(length|size)$|_equals$/.test(cd.check)) break;

        const max = cd.maximum ?? cd.length ?? cd.size;

        if (max >= 0) {
          if (cd.check !== 'max_length') fail(where, `size cap from ${cd.check}`);

          caps.push(`if items.len() > ${max} { p.push(Issue::new(Code::TooBig, ${rustStr(message({ code: 'too_big', origin: 'array', maximum: max, inclusive: true }, cd.error, def.error))}, Some(false))); return; }`);
        }
      }

      return [
        `let Some(Value::Array(items)) = &p.value else { ${typeIssue('array')} return; };`,
        ...caps,
        'let items = items.clone();',
        `p.value = Some(Value::Array(elements(p, items, ${fnFor(def.element, `${where}.item`)})));`,
      ];
    }
    case 'union': {
      const options = def.options.map((option, index) => fnFor(option, `${where}.${index}`));

      if (def.discriminator === undefined) {
        if (def.inclusive === false) fail(where, 'exclusive union');
        if (options.length === 1) return [`${options[0]}(p);`];

        return [`union(p, &[${options.join(', ')}], ${rustStr(message({ code: 'invalid_union', errors: [] }, def.error))});`];
      }

      if (def.unionFallback) fail(where, 'unionFallback');

      const map = new Map();

      def.options.forEach((option, index) => {
        for (const tag of option._zod.propValues?.[def.discriminator] ?? fail(where, 'option without a discriminator')) {
          map.set(tag, map.has(tag) ? null : options[index]);
        }
      });

      const claimed = [...map].filter(([, fn]) => fn !== null);
      const known = claimed.map(([tag]) => tag);
      const issue = { code: 'invalid_union', errors: [], options: known, path: [def.discriminator] };

      return [
        `if !matches!(p.value, Some(Value::Object(_))) { ${typeIssue('object')} return; }`,
        `let tag = p.value.as_ref().and_then(|value| value.get(${rustStr(def.discriminator)})).cloned();`,
        ...claimed.map(([tag, fn], index) => `${index ? 'else ' : ''}if ${matches([tag], 'tag.as_ref()', where)} { ${fn}(p); }`),
        `else { let mut issue = Issue::new(Code::InvalidUnion, ${rustStr(message(issue, def.error))}, None); issue.path = vec![PathKey::key(${rustStr(def.discriminator)})]; p.push(issue); }`,
      ];
    }
    case 'nullable':
      return [`if !matches!(p.value, Some(Value::Null)) { ${fnFor(def.innerType, `${where}.inner`)}(p); }`];
    case 'optional': {
      const inner = fnFor(def.innerType, `${where}.inner`);

      return def.innerType._zod.optin === 'defaulted'
        ? [`if p.value.is_none() { let mut r = Payload::new(None); ${inner}(&mut r); p.value = if r.issues.is_empty() { r.value } else { None }; } else { ${inner}(p); }`]
        : [`if p.value.is_some() { ${inner}(p); }`];
    }
    case 'default': {
      const fallback = value(def.defaultValue, where);

      return [`if p.value.is_none() { p.value = Some(${fallback}); return; }`, `${fnFor(def.innerType, `${where}.inner`)}(p);`, `if p.value.is_none() { p.value = Some(${fallback}); }`];
    }
    case 'prefault':
      return [`if p.value.is_none() { p.value = Some(${value(def.defaultValue, where)}); }`, `${fnFor(def.innerType, `${where}.inner`)}(p);`];
    case 'pipe':
      return [`${fnFor(def.in, `${where}.in`)}(p);`, `if p.issues.is_empty() { ${fnFor(def.out, `${where}.out`)}(p); } else { p.aborted = true; }`];
    case 'transform':
      return [`p.value = p.value.take().map(crate::refine::${hookFor('transform', schema, where, String(def.transform))});`];
    case 'intersection':
      return [`intersection(p, ${fnFor(def.left, `${where}.left`)}, ${fnFor(def.right, `${where}.right`)});`];
    case 'record': {
      const key = def.keyType._zod.def;

      if (key.type !== 'string' || key.checks?.length || def.valueType._zod.def.type !== 'unknown' || def.mode) {
        fail(where, 'only z.record(z.string(), z.unknown()) is supported');
      }

      return [
        `let Some(Value::Object(input)) = &p.value else { ${typeIssue('record')} return; };`,
        'p.value = Some(Value::Object(input.iter().filter(|(key, _)| *key != "__proto__").map(|(key, item)| (key.clone(), item.clone())).collect()));',
      ];
    }
    default:
      return fail(where, `unsupported type ${def.type}`);
  }
}

/** The condition zod gives every length check; the Rust checks apply under it alone. */
const LENGTH_WHEN = z.string().max(1)._zod.def.checks[0]._zod.def.when.toString();

/** The statements of one check: `[statements, runs when aborted]`. */
function check(owner, ch, where) {
  const def = ch._zod.def;
  const ownerError = ch === owner ? undefined : owner._zod.def.error;
  const abort = Boolean(def.abort);
  const msg = (issue) => rustStr(message(issue, def.error, ownerError));

  switch (def.check) {
    case 'max_length':
    case 'min_length': {
      if (def.when && def.when.toString() !== LENGTH_WHEN) fail(where, 'custom when');

      const big = def.check === 'max_length';
      const bound = big ? def.maximum : def.minimum;
      const issue = (origin) => ({ code: big ? 'too_big' : 'too_small', origin, [big ? 'maximum' : 'minimum']: bound, inclusive: true });
      const msgs = `&LengthMessages { string: ${msg(issue('string'))}, array: ${msg(issue('array'))} }`;

      return [`check_${def.check}(p, ${bound}, ${msgs}, ${abort});`, true];
    }
    case 'number_format': {
      if (def.format !== 'safeint') fail(where, `number format ${def.format}`);

      const notInt = msg({ code: 'invalid_type', expected: 'int', input: 1.5, format: 'safeint' });
      const tooBig = msg({ code: 'too_big', maximum: Number.MAX_SAFE_INTEGER, origin: 'int', inclusive: true });
      const tooSmall = msg({ code: 'too_small', minimum: Number.MIN_SAFE_INTEGER, origin: 'int', inclusive: true });

      return [`check_safeint(p, ${notInt}, ${tooBig}, ${tooSmall}, ${abort});`, false];
    }
    case 'greater_than':
    case 'less_than': {
      if (typeof def.value !== 'number') fail(where, 'non-number bound');

      const lower = def.check === 'greater_than';
      const issue = { code: lower ? 'too_small' : 'too_big', origin: 'number', [lower ? 'minimum' : 'maximum']: def.value, inclusive: def.inclusive };

      return [`check_bound(p, ${Number.isInteger(def.value) ? `${def.value}.0` : def.value}, ${Boolean(def.inclusive)}, ${lower}, ${msg(issue)}, ${abort});`, false];
    }
    case 'string_format': {
      if (def.format === 'url') {
        if (def.hostname || def.normalize) fail(where, 'url options');

        const http = def.protocol?.source === '^https?$';

        if (def.protocol && !http) fail(where, `url protocol ${def.protocol}`);

        return [`check_url(p, ${http}, ${msg({ code: 'invalid_format', format: 'url' })}, ${abort});`, false];
      }

      if (!def.pattern) fail(where, `format ${def.format} without a pattern`);

      const issue = { code: 'invalid_format', origin: 'string', format: def.format, pattern: String(def.pattern) };

      return [`check_pattern(p, &${regexFor(def.pattern, where)}, ${msg(issue)}, ${abort});`, false];
    }
    case 'custom': {
      if (def.when) fail(where, 'custom check with when');

      if (def.fn) {
        if (def.path?.length) fail(where, 'refine path');

        const hook = hookFor('refine', ch, where, String(def.fn));

        return [`if !crate::refine::${hook}(p.value.as_ref().unwrap_or(&Value::Null)) { p.push(Issue::new(Code::Custom, ${msg({ code: 'custom' })}, Some(${!abort}))); }`, false];
      }

      const hook = hookFor('super', ch, where, '');

      return [`let value = p.value.clone().unwrap_or(Value::Null); crate::refine::${hook}(&value, &mut RefineCtx::new(p));`, false];
    }
    default:
      return fail(where, `unsupported check ${def.check}`);
  }
}

function emit(schema, where) {
  const name = names.get(schema);
  const def = schema._zod.def;
  const checks = [...(schema._zod.traits.has('$ZodCheck') ? [schema] : []), ...(def.checks ?? [])];
  const lines = [];
  const body = parse(schema, where);
  const early = body.some((line) => line.includes('return;'));

  if (checks.length === 0) {
    lines.push(...body);
  } else {
    if (early) {
      lines.push('parse(p);', `fn parse(p: &mut Payload) {`, ...body.map((line) => `    ${line}`), '}');
    } else {
      lines.push(...body);
    }

    lines.push('let mut stopped = aborted(p, 0);');

    checks.forEach((ch, index) => {
      const [statements, when] = check(schema, ch, `${where}#${index}`);

      if (when) {
        lines.push(`{ let start = p.issues.len(); ${statements} if !stopped && p.issues.len() != start { stopped = aborted(p, start); } }`);
      } else {
        lines.push(`if !stopped { let start = p.issues.len(); ${statements} if p.issues.len() != start { stopped = aborted(p, start); } }`);
      }
    });

    lines.push('let _ = stopped;');
  }

  const doc = exported.has(schema) ? '' : `/// \`${where}\`\n#[doc(hidden)]\n`;

  bodies.push(`${doc}pub fn ${name}(p: &mut Payload) {\n${lines.map((line) => `    ${line}`).join('\n')}\n}\n`);
}

