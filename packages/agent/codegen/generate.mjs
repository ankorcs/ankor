function typeName(schema, where) {
  if (exported.has(schema)) return exported.get(schema);
  if (preferred.has(schema)) return preferred.get(schema);
  if (TYPE_NAMES[where]) return TYPE_NAMES[where];

  let name = pascal(where.replace(/\.(inner|in|item)\b/g, ''));

  while ([...typeNames.values()].includes(name) || [...exported.values()].includes(name)) name += 'Inline';

  return name;
}

function literalType(text) {
  if (!literalTypes.has(text)) literalTypes.set(text, `Lit${pascal(text) || 'Empty'}`);

  return literalTypes.get(text);
}

function isInt(schema) {
  return [schema, ...(schema._zod.def.checks ?? [])].some((ch) => ch._zod.def.check === 'number_format');
}

/** Fields each union option leaves to the enclosing tagged enums: the tags of every union above it. */
const exclusions = new Map();

function collectTags(schema, above) {
  const def = schema._zod.def;

  if (def.type !== 'union' || !def.discriminator) return;

  const here = [...above, def.discriminator];

  for (const option of def.options) {
    if ((exclusions.get(option)?.length ?? -1) < here.length) exclusions.set(option, here);

    collectTags(option, here);
  }
}

for (const schema of exported.keys()) collectTags(schema, []);

/** Names each shared anonymous type after its shortest path from an export, so nesting depth, not visiting order, decides. */
function nameByShortestPath() {
  const queue = [...exported].map(([schema, name]) => [schema, name]);
  const seen = new Set();

  while (queue.length) {
    const [schema, where] = queue.shift();

    if (!schema?._zod || seen.has(schema) || extern.has(schema)) continue;
    seen.add(schema);

    const def = schema._zod.def;
    const named = def.type === 'object' || def.type === 'enum' || (def.type === 'union' && def.discriminator);

    if (named && !exported.has(schema) && !preferred.has(schema) && !TYPE_NAMES[where]) {
      preferred.set(schema, typeName(schema, where));
    }

    const own = exported.get(schema) ?? preferred.get(schema) ?? TYPE_NAMES[where];

    if (def.type === 'object') {
      for (const [key, field] of Object.entries(def.shape)) queue.push([field, `${where}.${key}`]);
    } else if (def.type === 'array') {
      queue.push([def.element, `${where}.item`]);
    } else if (['nullable', 'optional', 'default', 'prefault'].includes(def.type)) {
      queue.push([def.innerType, where]);
    } else if (def.type === 'pipe') {
      queue.push([def.in, `${where}.in`], [def.out, where]);
    } else if (def.type === 'union') {
      def.options.forEach((option, index) => {
        if (def.discriminator && own) {
          const tag = [...(option._zod.propValues?.[def.discriminator] ?? [])][0];

          if (!exported.has(option) && !preferred.has(option) && tag !== undefined) preferred.set(option, `${own}${pascal(String(tag))}`);
        }

        queue.push([option, `${where}.${index}`]);
      });
    }
  }
}

/**
 * A union option leaves its tags to the enclosing tagged enum. When a field holds such an object
 * directly, no enum writes the tags, so the field writes them itself through a generated function.
 */
const tagWriters = new Map();

function fieldTags(member, where) {
  let target = member;

  while (['nullable', 'array'].includes(target._zod.def.type)) target = target._zod.def.innerType ?? target._zod.def.element;

  // A type from another run, such as the protocol's in the agent's contract, brings its left-out
  // tags along, since this run never saw the union it is an option of.
  const excluded = exclusions.get(target) ?? extern.get(target)?.tags?.map(([key]) => key) ?? [];

  if (excluded.length === 0 || (target._zod.def.type !== 'object' && !extern.has(target))) return undefined;
  if (target !== member) fail(where, 'a tagged union option inside a nullable or array field');

  if (!tagWriters.has(target)) {
    const name = `write_${snake(rustType(target, where).split('::').at(-1))}_tagged`;
    const tags = excluded.map((key) => `(${rustStr(key)}, serde_json::json!(${JSON.stringify([...target._zod.propValues[key]][0])}))`);

    tagWriters.set(target, name);
    typeDefs.push(
      `/// Writes a \`${rustType(target, where)}\` with the tags its union option leaves out.\nfn ${name}<S: serde::Serializer>(value: &${rustType(target, where)}, serializer: S) -> Result<S::Ok, S::Error> {\n    let mut value = serde_json::to_value(value).map_err(serde::ser::Error::custom)?;\n\n    for (key, tag) in [${tags.join(', ')}] {\n        value = ${root}::support::with_tag(key, tag, value);\n    }\n\n    value.serialize(serializer)\n}\n`,
    );
  }

  return tagWriters.get(target);
}

/** The Rust type of a schema's parsed output, defining named types on first use. */
function rustType(schema, where) {
  if (extern.get(schema)?.type) return extern.get(schema).type;

  const def = schema._zod.def;
  const excluded = exclusions.get(schema) ?? [];

  switch (def.type) {
    case 'string':
      return 'String';
    case 'number':
      return isInt(schema) ? 'i64' : 'f64';
    case 'boolean':
      return 'bool';
    case 'unknown':
    case 'intersection':
      return 'Value';
    case 'record':
      return 'serde_json::Map<String, Value>';
    case 'array':
      return `Vec<${rustType(def.element, `${where}.item`)}>`;
    case 'nullable':
      return `Option<${rustType(def.innerType, where)}>`;
    case 'optional':
    case 'default':
    case 'prefault':
      return rustType(def.innerType, where);
    case 'pipe':
      if (def.out._zod.def.type === 'transform') {
        rustType(def.in, `${where}.in`);
        if (exported.has(schema)) roundTrips.push([exported.get(schema), 'crate::config::AgentConfig']);
        return 'crate::config::AgentConfig';
      }

      return rustType(def.out, where);
    case 'literal': {
      const kinds = new Set(def.values.map((v) => typeof v));

      if (kinds.size !== 1) fail(where, 'mixed literal');
      if (kinds.has('number')) return def.values.every(Number.isInteger) ? 'i64' : 'f64';
      if (kinds.has('boolean')) return 'bool';
      if (def.values.length > 1) return 'String';

      return literalType(def.values[0]);
    }
    case 'enum':
    case 'object':
    case 'union':
      break;
    default:
      return fail(where, `no Rust type for ${def.type}`);
  }

  if (def.type === 'union' && !def.discriminator) {
    const kinds = def.options.map((option) => rustType(option, where));

    if (kinds.every((kind) => kind === 'i64')) return 'i64';
    if (kinds.every((kind) => kind === 'String' || kind.startsWith('Lit'))) return 'String';

    return fail(where, `plain union of ${kinds}`);
  }

  if (typeNames.has(schema)) return typeNames.get(schema);

  const name = typeName(schema, where);

  typeNames.set(schema, name);

  const derive = '#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]';
  const typeDoc = rustDoc(docs.at(exported.get(schema) ?? where));

  if (def.type === 'enum') {
    const values = [...schema._zod.values];
    // `Self` names the type in Rust, even as a raw identifier; the wire value stays in `serde(rename)`.
    const variant = (value) => {
      const name = pascal(value === value.toUpperCase() ? value.toLowerCase() : value);

      return name === 'Self' ? 'SelfValue' : name;
    };
    const variants = values.map((value) => `    #[serde(rename = ${rustStr(value)})]\n    ${variant(value)},`);

    typeDefs.push(`${typeDoc}#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]\npub enum ${name} {\n${variants.join('\n')}\n}\n\nimpl ${name} {\n    /// Every value, in the contract's order.\n    pub const ALL: &'static [Self] = &[${values.map((value) => `Self::${variant(value)}`).join(', ')}];\n}\n`);
    roundTrips.push([exported.get(schema), name]);
  } else if (def.type === 'object') {
    const fields = [];

    for (const [key, member] of Object.entries(def.shape)) {
      if (excluded.includes(key)) continue;

      const optional = member._zod.optout === 'optional';
      let inner = member;

      while (['optional', 'default', 'prefault'].includes(inner._zod.def.type)) inner = inner._zod.def.innerType;

      const base = rustType(member, `${where}.${key}`);
      const attrs = snake(key) === key ? [] : [`#[serde(rename = ${rustStr(key)})]`];
      const fieldName = field(snake(key));
      const fieldDoc = rustDoc(docs.at(`${exported.get(schema) ?? where}.${key}`) ?? docs.at(`${where}.${key}`), '    ');
      const tags = fieldTags(inner, `${where}.${key}`);

      if (tags) {
        attrs.push(`#[serde(serialize_with = "${tags}")]`);
      }

      if (optional && inner._zod.def.type === 'nullable') {
        attrs.push(`#[serde(default, skip_serializing_if = "Option::is_none", with = "${root}::support::double_option")]`);
        fields.push(`${fieldDoc}${attrs.map((a) => `    ${a}\n`).join('')}    pub ${fieldName}: Option<${base}>,`);
      } else if (optional) {
        attrs.push('#[serde(default, skip_serializing_if = "Option::is_none")]');
        fields.push(`${fieldDoc}${attrs.map((a) => `    ${a}\n`).join('')}    pub ${fieldName}: Option<${base}>,`);
      } else {
        fields.push(`${fieldDoc}${attrs.map((a) => `    ${a}\n`).join('')}    pub ${fieldName}: ${base},`);
      }
    }

    if (def.catchall) {
      fields.push('    #[serde(flatten)]\n    pub extra: serde_json::Map<String, Value>,');
    }

    typeDefs.push(`${typeDoc}${derive}\npub struct ${name} {\n${fields.join('\n')}\n}\n\nimpl ${name} {\n    /// The keys this object takes.\n    pub const FIELDS: &'static [&'static str] = &[${Object.keys(def.shape).map(rustStr).join(', ')}];\n}\n`);

    if (excluded.length === 0) roundTrips.push([exported.get(schema), name]);
  } else {
    const disc = def.discriminator;
    const options = def.options.map((option, index) => {
      const tags = [...option._zod.propValues[disc]];

      if (tags.length !== 1) fail(where, 'option with several tags');
      if (!preferred.has(option)) preferred.set(option, `${name}${pascal(String(tags[0]))}`);

      return { tag: tags[0], type: rustType(option, `${where}.${index}`), name: exported.get(option) };
    });

    if (options.every((option) => typeof option.tag === 'string')) {
      const variants = options.map((option) => `    #[serde(rename = ${rustStr(option.tag)})]\n    ${pascal(option.tag)}(${option.type}),`);

      typeDefs.push(`${typeDoc}${derive}\n#[serde(tag = ${rustStr(disc)})]\npub enum ${name} {\n${variants.join('\n')}\n}\n\nimpl ${name} {\n    /// The \`${disc}\` of each variant.\n    pub const TAGS: &'static [&'static str] = &[${options.map((option) => rustStr(option.tag)).join(', ')}];\n}\n`);
    } else if (options.every((option) => typeof option.tag === 'boolean')) {
      const variant = (option) => (option.name?.startsWith(name) ? option.name.slice(name.length) : pascal(String(option.tag)));
      const arms = options.map((option) => `            Some(Value::Bool(${option.tag})) => serde_json::from_value(value).map(Self::${variant(option)}),`);

      typeDefs.push(`${typeDoc}#[derive(Debug, Clone, PartialEq)]
pub enum ${name} {
${options.map((option) => `    ${variant(option)}(${option.type}),`).join('\n')}
}

impl Serialize for ${name} {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        let (tag, value) = match self {
${options.map((option) => `            Self::${variant(option)}(inner) => (${option.tag}, serde_json::to_value(inner).map_err(serde::ser::Error::custom)?),`).join('\n')}
        };

        ${root}::support::with_tag(${rustStr(disc)}, Value::Bool(tag), value).serialize(serializer)
    }
}

impl<'de> Deserialize<'de> for ${name} {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = Value::deserialize(deserializer)?;

        match value.get(${rustStr(disc)}) {
${arms.join('\n')}
            _ => return Err(serde::de::Error::custom("unknown ${disc}")),
        }
        .map_err(serde::de::Error::custom)
    }
}
`);
    } else {
      fail(where, 'mixed discriminator values');
    }

    if (excluded.length === 0) roundTrips.push([exported.get(schema), name]);
  }

  return name;
}

