/// A stock map every install has: a workshop launch boots on it before it switches maps.
pub(crate) const STOCK_BOOT_MAP: &str = "de_dust2";

const GENERATED: &str = "// generated by @ankorcs/agent - overwritten on every launch, do not edit";

/// The protocol already refuses control characters; a quote would end the cfg string early.
fn quote(value: &str) -> String {
    format!("\"{}\"", value.replace('"', ""))
}

/// Demos are recorded through GOTV, so a match that records one runs GOTV even unlisted.
fn records_demo(config: &ServerLaunchConfig) -> bool {
    config.r#match.as_ref().is_some_and(|game| game.record_demo)
}

/// Everything the launch sets, in one file so that it all runs together. The plugin execs it on one
/// console line with Ankor's cfgs, which CS2 runs on a single tick. It runs on every map load and
/// when a match goes live, after the mode cfg and `ankor/base`, so it outlasts the resets both make.
#[must_use]
pub(crate) fn render_launch_cfg(config: &ServerLaunchConfig) -> String {
    let mut lines = vec![GENERATED.to_owned()];

    if let Some(hostname) = config.hostname.as_deref().filter(|name| !name.is_empty()) {
        lines.push(format!("hostname {}", quote(hostname)));
    }

    if let Some(tv) = &config.gotv {
        lines.push(format!("tv_delay {}", tv.delay_seconds));

        if let Some(password) = tv.password.as_deref().filter(|password| !password.is_empty()) {
            lines.push(format!("tv_password {}", quote(password)));
        }
    } else if records_demo(config) {
        // GOTV runs only to record the demo. A password that nobody receives keeps spectators out,
        // so there is nothing to delay.
        lines.push("tv_delay 0".to_owned());
        lines.push(format!("tv_password {}", quote(&hex::encode(rand::random::<[u8; 8]>()))));
    }

    if let Some(game) = &config.r#match {
        // A restore plays on under the rules its map was played under.
        let (max_rounds, overtime, overtime_max_rounds, friendly_fire) = match &game.restore {
            Some(restore) => (restore.rules.max_rounds, restore.rules.overtime, restore.rules.overtime_max_rounds, restore.rules.friendly_fire),
            None => (game.rules.max_rounds, game.rules.overtime, game.rules.overtime_max_rounds, game.rules.friendly_fire),
        };

        lines.push(format!("mp_maxrounds {max_rounds}"));
        lines.push(format!("mp_overtime_enable {}", u8::from(overtime)));
        lines.push(format!("mp_overtime_maxrounds {overtime_max_rounds}"));

        // Grenades always hurt teammates; the lobby's switch only adds bullets and melee.
        if !friendly_fire {
            lines.push("ff_damage_reduction_bullets 0".to_owned());
            lines.push("ff_damage_reduction_other 0".to_owned());
        }
    }

    lines.extend(config.exec.iter().map(|cfg| format!("exec {cfg}")));
    // A match server leaves out the commands its plugin refuses from the console.
    let blocked = blocked_launch_commands(config);
    lines.extend(config.commands.iter().filter(|line| !blocked.iter().any(|(_, dropped)| dropped == line)).cloned());

    format!("{}\n", lines.join("\n"))
}

/// The lines of the launch's `commands` that a match server leaves out, each with the blocked
/// command it names. A launch without a match keeps them all.
#[must_use]
pub(crate) fn blocked_launch_commands(config: &ServerLaunchConfig) -> Vec<(&'static str, &String)> {
    if config.r#match.is_none() {
        return Vec::new();
    }
    config.commands.iter().filter_map(|line| blocked_command(line).map(|blocked| (blocked, line))).collect()
}

/// The first command of `line` that [`MATCH_BLOCKED_COMMANDS`] names, as the plugin finds it in a
/// `console_command`. The line splits on every `;`, quoted or not, so a split the engine would not
/// make can only block more. The engine matches command names in any case.
fn blocked_command(line: &str) -> Option<&'static str> {
    line.split([';', '\n', '\r']).find_map(|command| {
        let name = command.trim_start_matches([' ', '\t', '"']).split([' ', '\t', '"']).next().unwrap_or_default();
        MATCH_BLOCKED_COMMANDS.iter().copied().find(|blocked| blocked.eq_ignore_ascii_case(name))
    })
}

/// The engine's backup file a restore loads.
#[must_use]
pub(crate) fn render_restore_file(config: &ServerLaunchConfig) -> Option<String> {
    config.r#match.as_ref()?.restore.as_ref().map(|restore| restore.file.clone())
}

/// The plugin's `SwiftlyS2` config, which skips comments and falls back to defaults on bad values.
#[must_use]
pub(crate) fn render_plugin_config(config: &ServerLaunchConfig) -> String {
    let body = json!({ "Chat": { "Tag": config.chat_tag.text, "TagColor": config.chat_tag.color } });

    format!("{GENERATED}\n{}\n", serde_json::to_string_pretty(&body).unwrap_or_default())
}

/// The match the plugin plays; `None` without one, so the slot has no match file.
#[must_use]
pub(crate) fn render_match_config(config: &ServerLaunchConfig) -> Option<String> {
    config.r#match.as_ref().and_then(|game| serde_json::to_string(game).ok())
}

fn mode_args(mode: GameMode) -> (u64, u64) {
    match mode {
        GameMode::Casual => (game_mode_args::casual::GAME_TYPE, game_mode_args::casual::GAME_MODE),
        GameMode::Competitive => (game_mode_args::competitive::GAME_TYPE, game_mode_args::competitive::GAME_MODE),
        GameMode::Wingman => (game_mode_args::wingman::GAME_TYPE, game_mode_args::wingman::GAME_MODE),
        GameMode::Rush => (game_mode_args::rush::GAME_TYPE, game_mode_args::rush::GAME_MODE),
        GameMode::ArmsRace => (game_mode_args::arms_race::GAME_TYPE, game_mode_args::arms_race::GAME_MODE),
        GameMode::Demolition => (game_mode_args::demolition::GAME_TYPE, game_mode_args::demolition::GAME_MODE),
        GameMode::Deathmatch => (game_mode_args::deathmatch::GAME_TYPE, game_mode_args::deathmatch::GAME_MODE),
        GameMode::Custom => (game_mode_args::custom::GAME_TYPE, game_mode_args::custom::GAME_MODE),
    }
}

/// Captures belong to a match that sends statistics, the only kind with an event history to compare.
#[must_use]
pub(crate) fn captures_debug(launch: &ServerLaunchConfig) -> bool {
    launch.r#match.as_ref().is_some_and(|game| game.debug_capture && game.send_statistics)
}

/// A game server's environment. It has no `-nomaster`, because with it CS2 answers no server
/// queries and Steam calls a `steam://connect` target unresponsive.
#[must_use]
pub(crate) fn render_container_env(slot: &ConfiguredSlot, config: &ServerLaunchConfig, plugin_url: &str, allocation_id: &str) -> BTreeMap<String, String> {
    let (game_type, game_mode) = mode_args(config.game_mode);
    let mut env = BTreeMap::from([
        (cs2_env::PORT.to_owned(), slot.port.to_string()),
        (cs2_env::TV_PORT.to_owned(), slot.tv_port.to_string()),
        (cs2_env::MAX_PLAYERS.to_owned(), config.max_players.to_string()),
        (cs2_env::GAME_TYPE.to_owned(), game_type.to_string()),
        (cs2_env::GAME_MODE.to_owned(), game_mode.to_string()),
        (cs2_env::TV_ENABLE.to_owned(), if config.gotv.is_some() || records_demo(config) { "1" } else { "0" }.to_owned()),
        (cs2_env::START_MAP.to_owned(), config.map_name.clone().unwrap_or_else(|| STOCK_BOOT_MAP.to_owned())),
        (ankor_env::WS_URL.to_owned(), plugin_url.to_owned()),
        (ankor_env::ALLOCATION_ID.to_owned(), allocation_id.to_owned()),
        (cs2_env::SRCDS_TOKEN.to_owned(), slot.gslt.clone()),
    ]);

    if let Some(password) = config.game_password.as_deref().filter(|password| !password.is_empty()) {
        env.insert(cs2_env::GAME_PASSWORD.to_owned(), password.to_owned());
    }

    if captures_debug(config) {
        env.insert(ankor_env::DEBUG_CAPTURE_DIR.to_owned(), DEBUG_CAPTURE_DIR.to_owned());
    }

    if let Some(workshop) = &config.workshop_id {
        env.insert(cs2_env::WORKSHOP_MAP.to_owned(), workshop.clone());

        // Without the key the engine cannot download the map after the bootstrap level.
        if let Some(key) = config.steam_web_api_key.as_deref().filter(|key| !key.is_empty()) {
            env.insert(cs2_env::AUTH_KEY.to_owned(), key.to_owned());
        }
    }

    env
}

#[must_use]
pub(crate) fn render_update_env(mode: Cs2UpdateMode) -> BTreeMap<String, String> {
    let reinstall = mode == Cs2UpdateMode::Reinstall;

    BTreeMap::from([
        (cs2_env::UPDATE_ONLY.to_owned(), "1".to_owned()),
        (cs2_env::VALIDATE.to_owned(), if mode == Cs2UpdateMode::Verify { "1" } else { "0" }.to_owned()),
        (cs2_env::REINSTALL.to_owned(), if reinstall { "1" } else { "0" }.to_owned()),
        (cs2_env::MIN_FREE_GB.to_owned(), if reinstall { CS2_REINSTALL_MIN_FREE_GB } else { CS2_UPDATE_MIN_FREE_GB }.to_string()),
    ])
}

#[must_use]
pub(crate) fn env_to_array(env: &BTreeMap<String, String>) -> Vec<String> {
    env.iter().map(|(key, value)| env_entry(key, value)).collect()
}

/// A container environment entry, `KEY=value`, as Docker takes and reports it.
#[must_use]
pub(crate) fn env_entry(key: &str, value: impl std::fmt::Display) -> String {
    format!("{key}={value}")
}

/// The value of `key` among `KEY=value` entries, as [`env_entry`] writes them.
#[must_use]
pub(crate) fn env_value<'a>(entries: impl IntoIterator<Item = &'a str>, key: &str) -> Option<&'a str> {
    entries.into_iter().find_map(|entry| entry.strip_prefix(key)?.strip_prefix('='))
}

#[must_use]
pub(crate) fn match_id_of(launch: &ServerLaunchConfig) -> Option<String> {
    launch.r#match.as_ref()?.match_id.clone()
}

