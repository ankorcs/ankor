    #[test]
    fn the_update_container_is_the_only_one_with_a_writable_install_volume() {
        let spec = crate::install::build_update_spec(&agent_config(&json!({})), "ff00ff", "00000000-0000-4000-8000-00000000a0a0", Cs2UpdateMode::Verify, false);

        assert_eq!(spec.name, "ankor-update-ff00ff");
        assert_eq!(spec.image, agent_config(&json!({})).cs2_image);
        assert_eq!(
            spec.volumes,
            [crate::host_layout::VolumeMount { volume: "ankor_cs2_data".to_owned(), target: "/home/steam/cs2-dedicated".to_owned(), read_only: false }]
        );
        assert!(spec.binds.is_empty());
        assert_eq!(spec.network_mode, crate::docker::NetworkMode::Bridge);
        // It runs for minutes, so the exit wait is attached long before Docker removes it.
        assert!(spec.auto_remove);
        assert_eq!(spec.env, env_to_array(&render_update_env(Cs2UpdateMode::Verify)));
        assert!(spec.env.contains(&format!("{}=1", cs2_env::UPDATE_ONLY)));
        assert!(spec.env.contains(&format!("{}=1", cs2_env::VALIDATE)));
        // steamcmd is the only installer the image carries, so there is nothing to pass.
        assert!(!spec.env.iter().any(|entry| entry.starts_with("CS2_INSTALLER")));
        assert_eq!(spec.labels["ankor.role"], "update");
        assert!(!spec.labels.contains_key("ankor.overlay"));
        // A background download stays on Docker's baseline CPU weight, so the game outranks it under contention.
        assert_eq!(spec.cpu_shares, None);
    }

    #[test]
    fn asks_steamcmd_to_verify_only_in_verify_mode_and_to_wipe_only_in_reinstall_mode() {
        let env = |mode| crate::install::build_update_spec(&agent_config(&json!({})), "ff00ff", "00000000-0000-4000-8000-00000000a0a0", mode, false).env;
        let update = env(Cs2UpdateMode::Update);
        let reinstall = env(Cs2UpdateMode::Reinstall);

        // A delta update is the default on every path, not an hour of re-hashing 67 GB.
        for entry in [format!("{}=0", cs2_env::VALIDATE), format!("{}=0", cs2_env::REINSTALL), format!("{}={CS2_UPDATE_MIN_FREE_GB}", cs2_env::MIN_FREE_GB)] {
            assert!(update.contains(&entry), "{entry}");
        }

        // Verifying an install steamcmd is about to write from nothing buys nothing, so a reinstall
        // asks for the larger free-space floor instead.
        for entry in [format!("{}=0", cs2_env::VALIDATE), format!("{}=1", cs2_env::REINSTALL), format!("{}={CS2_REINSTALL_MIN_FREE_GB}", cs2_env::MIN_FREE_GB)]
        {
            assert!(reinstall.contains(&entry), "{entry}");
        }
    }

